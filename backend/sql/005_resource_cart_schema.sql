  content_mode = 'vr',
  headset_brand = 'pico',
  vr_room_mode = 'pico',
  duration_minutes = coalesce(duration_minutes, 12),
  updated_at = now()
where slug in ('panda-vr', 'dino-vr');

update public.events
set
  event_type = 'game',
  content_mode = 'game',
  headset_brand = 'pico',
  vr_room_mode = 'none',
  duration_minutes = coalesce(duration_minutes, 12),
  updated_at = now()
where slug in ('game-a', 'game-b', 'game-c');

-- 10. Resource consumption rules.
-- Terracotta consumes HTC headsets and VR Show Room capacity.
insert into public.event_resource_requirements (
  event_id,
  resource_id,
  units_per_ticket,
  created_at,
  updated_at
)
select e.id, r.id, 1, now(), now()
from public.events e
join public.resources r on r.code in ('htc_headsets', 'vr_show_room')
where e.slug in ('terracotta-warriors', 'terracotta-army-vr', 'terracotta-warriors-vr')
on conflict (event_id, resource_id) do update
set
  units_per_ticket = excluded.units_per_ticket,
  updated_at = now();

-- Panda and Dino consume Pico headsets and VR Show Room capacity.
