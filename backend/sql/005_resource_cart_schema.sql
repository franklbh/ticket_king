-- 11. Indexes for availability, checkout, and webhook/payment lookups.
create index if not exists idx_slots_event_time
  on public.slots (event_id, business_date, start_time, end_time);

create index if not exists idx_slots_business_time
  on public.slots (business_date, start_time, end_time);

create index if not exists idx_orders_provider_reference
  on public.orders (payment_provider, provider_reference);

create index if not exists idx_order_items_order_id
  on public.order_items (order_id);

create index if not exists idx_order_items_slot_id
  on public.order_items (slot_id);

create index if not exists idx_order_items_event_slot
  on public.order_items (event_id, slot_id);

create index if not exists idx_tickets_order_item_id
  on public.tickets (order_item_id);

create index if not exists idx_event_resource_requirements_event_id
  on public.event_resource_requirements (event_id);
